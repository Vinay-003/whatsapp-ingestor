#!/usr/bin/env bash
# Creates database access for the ingestion service and writes DATABASE_URL
# into .env.
#
# Why this exists:
#   * The Supabase CLI connects with a temporary login role, so the project's
#     database password is never available to this project.
#   * The service needs a normal, long-lived login it can use from Render
#     (Render's filesystem is ephemeral, so the session must live in the
#     database).
#   * The connection pooler only routes the `postgres` user, so a custom role
#     cannot be reached through it. A least-privilege role `ingestor_app` is
#     still created for the future (it can be used the moment the pooler can
#     route it, or over a direct IPv6 connection).
#
# The generated migration contains a password and is gitignored.
#
# Usage: scripts/create-db-access.sh
set -euo pipefail
cd "$(dirname "$0")/.."

PROJECT_REF="${SUPABASE_PROJECT_REF:-ykllmcwljsfeluhpvzbv}"
REGION="${SUPABASE_REGION:-ap-southeast-2}"
PASSWORD_FILE=".env.dbpassword"
MIGRATION="supabase/migrations/003_db_access.sql"

if [ ! -f "$PASSWORD_FILE" ]; then
  node -e "console.log(require('crypto').randomBytes(24).toString('base64url'))" > "$PASSWORD_FILE"
  chmod 600 "$PASSWORD_FILE"
fi
PASSWORD="$(cat "$PASSWORD_FILE")"

cat > "$MIGRATION" <<SQL
-- Generated by scripts/create-db-access.sh — contains a password, do not commit.

-- Long-lived password for the pooler-routable role.
alter role postgres with password '${PASSWORD}';

-- Least-privilege role for the ingestion service. Not reachable through the
-- pooler yet (the pooler only routes the postgres user), but ready for a
-- direct connection or a pooler extension.
do \$\$
begin
  if exists (select 1 from pg_roles where rolname = 'ingestor_app') then
    execute format('alter role ingestor_app with login password %L', '${PASSWORD}');
  else
    execute format('create role ingestor_app with login password %L', '${PASSWORD}');
  end if;
end
\$\$;

grant usage on schema public, connector to ingestor_app;
grant select, insert, update, delete on all tables in schema public to ingestor_app;
grant select, insert, update, delete on all tables in schema connector to ingestor_app;
grant usage, select on all sequences in schema public to ingestor_app;
SQL

echo "Applying migration..."
supabase db push --linked

DB_URL="postgresql://postgres.${PROJECT_REF}:${PASSWORD}@aws-0-${REGION}.pooler.supabase.com:5432/postgres"
echo
echo "DATABASE_URL (password hidden):"
echo "  postgresql://postgres.${PROJECT_REF}:***@aws-0-${REGION}.pooler.supabase.com:5432/postgres"
printf '%s' "$DB_URL" > .env.database_url
chmod 600 .env.database_url
echo
echo "Saved to .env.database_url (gitignored). Append it to .env as DATABASE_URL=..."
